using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace ObFramework.Generator.Unity
{
    /// <summary>
    /// Emits the additional partial declaration of a generated Unity controller that implements
    /// <c>IGeneratedUIBinding</c>: typed View storage, display-cycle subscriptions, OneWay/TwoWay
    /// data updates and direct command dispatch. All bindings are resolved at generation time from
    /// source conventions; the generated code contains no reflection or runtime lookup.
    /// </summary>
    internal static class UIBindingEmitter
    {
        private const string Indent1 = "    ";
        private const string Indent2 = Indent1 + "    ";
        private const string Indent3 = Indent2 + "    ";
        private const string Indent4 = Indent3 + "    ";
        private const string BindingNamespace = "global::ObFramework.Adapter.Unity.ViewBinding";

        public static void Emit(GeneratorExecutionContext context, UIBindingPlan plan)
        {
            var source = Build(plan);
            var hint = plan.Controller.ToDisplayString() + ".UIBinding.g.cs";
            context.AddSource(hint, SourceText.From(source, Encoding.UTF8));
        }

        internal static string Build(UIBindingPlan plan)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable disable");
            var space = plan.Controller.ContainingNamespace;
            var hasNamespace = space != null && !space.IsGlobalNamespace;
            if (hasNamespace)
            {
                sb.Append("namespace ").Append(space.ToDisplayString()).AppendLine();
                sb.AppendLine("{");
            }

            var controller = "@" + plan.Controller.Name;
            sb.Append(Indent1).Append("partial class ").Append(controller).Append(" : ")
                .Append(BindingNamespace).Append(".IGeneratedUIBinding").AppendLine();
            sb.Append(Indent1).AppendLine("{");

            EmitFields(sb, plan);
            EmitViewProperty(sb, plan);
            EmitInterfaceImplementation(sb);
            EmitLifecycleHooks(sb, plan);
            EmitRefreshBindings(sb, plan);
            EmitReleaseBindings(sb, plan);
            EmitPropertyChangedHandler(sb, plan);
            EmitCommandStateChangedHandler(sb, plan);
            foreach (var binding in plan.Data)
                EmitDataBinding(sb, binding);
            foreach (var binding in plan.Commands)
                EmitCommandBinding(sb, binding);

            sb.Append(Indent1).AppendLine("}");
            if (hasNamespace)
                sb.AppendLine("}");
            return sb.ToString();
        }

        private static void EmitFields(StringBuilder sb, UIBindingPlan plan)
        {
            sb.Append(Indent2).Append("private ").Append(plan.ViewTypeExpression).AppendLine(" __view;");
            sb.Append(Indent2).AppendLine("private bool __uiBound;");
            sb.Append(Indent2).AppendLine("private bool __uiUpdating;");
            foreach (var binding in plan.Commands)
            {
                if (!binding.HasStoredValue)
                    continue;
                sb.Append(Indent2).Append("private ").Append(binding.StoredValueTypeExpression)
                    .Append(' ').Append(binding.StoredValueFieldName).AppendLine(";");
            }
            sb.AppendLine();
        }

        private static void EmitViewProperty(StringBuilder sb, UIBindingPlan plan)
        {
            if (plan.Controller.GetMembers("View").Length != 0)
                return;
            sb.Append(Indent2).Append("public ").Append(plan.ViewTypeExpression).AppendLine(" View");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("get { return __view; }");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static void EmitInterfaceImplementation(StringBuilder sb)
        {
            sb.Append(Indent2).Append("void ").Append(BindingNamespace)
                .AppendLine(".IGeneratedUIBinding.RefreshBindings()");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("__RefreshBindings();");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static void EmitLifecycleHooks(StringBuilder sb, UIBindingPlan plan)
        {
            sb.Append(Indent2).Append("partial void __UIBindingCreated(").Append(plan.ViewTypeExpression)
                .AppendLine(" view)");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("__view = view;");
            sb.Append(Indent3).AppendLine("if (isActiveAndEnabled)");
            sb.Append(Indent4).AppendLine("__RefreshBindings();");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();

            sb.Append(Indent2).AppendLine("partial void __OnUIBindingEnabled()");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("__RefreshBindings();");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();

            sb.Append(Indent2).AppendLine("partial void __OnUIBindingDisabled()");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("__ReleaseBindings();");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();

            sb.Append(Indent2).AppendLine("partial void __OnUIBindingDestroyed()");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("__ReleaseBindings();");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static void EmitRefreshBindings(StringBuilder sb, UIBindingPlan plan)
        {
            var subscribesProperty = plan.Data.Count > 0;
            var subscribesCommandState = plan.Commands.Any(item => item.HasCanExecute);

            sb.Append(Indent2).AppendLine("private void __RefreshBindings()");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("if (__view == null)");
            sb.Append(Indent4).AppendLine("return;");
            sb.Append(Indent3).AppendLine("if (!__uiBound)");
            sb.Append(Indent3).AppendLine("{");
            sb.Append(Indent4).AppendLine("__uiBound = true;");
            if (subscribesProperty)
                sb.Append(Indent4).AppendLine("__view.PropertyChanged += __OnViewPropertyChanged;");
            if (subscribesCommandState)
                sb.Append(Indent4).AppendLine("__view.CommandStateChanged += __OnViewCommandStateChanged;");
            foreach (var line in SubscribeLines(plan, subscribe: true))
                sb.Append(Indent4).AppendLine(line);
            sb.Append(Indent3).AppendLine("}");
            foreach (var binding in plan.Data)
                sb.Append(Indent3).Append("__").Append("RefreshData").Append(binding.MemberName).AppendLine("();");
            foreach (var binding in plan.Commands)
            {
                if (!binding.HasCanExecute)
                    continue;
                sb.Append(Indent3).Append("__RefreshCommand").Append(binding.MemberName).AppendLine("();");
            }
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static void EmitReleaseBindings(StringBuilder sb, UIBindingPlan plan)
        {
            var subscribesProperty = plan.Data.Count > 0;
            var subscribesCommandState = plan.Commands.Any(item => item.HasCanExecute);

            sb.Append(Indent2).AppendLine("private void __ReleaseBindings()");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("if (!__uiBound)");
            sb.Append(Indent4).AppendLine("return;");
            sb.Append(Indent3).AppendLine("__uiBound = false;");
            sb.Append(Indent3).AppendLine("if (__view != null)");
            sb.Append(Indent3).AppendLine("{");
            if (subscribesProperty)
                sb.Append(Indent4).AppendLine("__view.PropertyChanged -= __OnViewPropertyChanged;");
            if (subscribesCommandState)
                sb.Append(Indent4).AppendLine("__view.CommandStateChanged -= __OnViewCommandStateChanged;");
            sb.Append(Indent3).AppendLine("}");
            foreach (var line in SubscribeLines(plan, subscribe: false))
                sb.Append(Indent3).AppendLine(line);
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static IEnumerable<string> SubscribeLines(UIBindingPlan plan, bool subscribe)
        {
            foreach (var binding in plan.Data)
            {
                if (!binding.TwoWay || binding.HandlerMethod == null)
                    continue;
                var member = EventMember(binding.Control);
                if (member == null)
                    continue;
                yield return SubscribeLine(binding.FieldName, member, binding.HandlerMethod!, subscribe);
            }
            foreach (var binding in plan.Commands)
            {
                var member = CommandEventMember(binding.Control);
                if (member == null)
                    continue;
                yield return SubscribeLine(binding.FieldName, member, binding.HandlerMethod, subscribe);
            }
        }

        private static string SubscribeLine(string field, string member, string handler, bool subscribe)
        {
            var method = subscribe ? "AddListener" : "RemoveListener";
            return "if (" + field + " != null) " + field + "." + member + "." + method + "(" + handler + ");";
        }

        private static string? EventMember(ControlKind control)
        {
            switch (control)
            {
                case ControlKind.InputField:
                case ControlKind.TmpInputField:
                case ControlKind.Toggle:
                case ControlKind.Slider:
                    return "onValueChanged";
                default:
                    return null;
            }
        }

        private static string? CommandEventMember(ControlKind control)
        {
            switch (control)
            {
                case ControlKind.Button:
                    return "onClick";
                case ControlKind.InputField:
                case ControlKind.TmpInputField:
                    return "onEndEdit";
                case ControlKind.Toggle:
                case ControlKind.Slider:
                    return "onValueChanged";
                default:
                    return null;
            }
        }

        private static void EmitPropertyChangedHandler(StringBuilder sb, UIBindingPlan plan)
        {
            if (plan.Data.Count == 0)
                return;

            var order = new List<string>();
            var calls = new Dictionary<string, List<string>>(StringComparer.Ordinal);
            foreach (var binding in plan.Data)
            {
                if (!calls.TryGetValue(binding.PropertyName, out var list))
                {
                    list = new List<string>();
                    calls.Add(binding.PropertyName, list);
                    order.Add(binding.PropertyName);
                }
                list.Add(binding.RefreshMethod + "();");
            }

            sb.Append(Indent2).AppendLine("private void __OnViewPropertyChanged(string __propertyName)");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("switch (__propertyName)");
            sb.Append(Indent3).AppendLine("{");
            foreach (var name in order)
            {
                sb.Append(Indent4).Append("case ").Append(SymbolDisplay.FormatLiteral(name, quote: true)).AppendLine(":");
                foreach (var call in calls[name])
                    sb.Append(Indent4).Append(Indent1).AppendLine(call);
                sb.Append(Indent4).AppendLine("    break;");
            }
            sb.Append(Indent3).AppendLine("}");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static void EmitCommandStateChangedHandler(StringBuilder sb, UIBindingPlan plan)
        {
            var filtered = new List<CommandBindingPlan>();
            var anyCommand = new List<CommandBindingPlan>();
            foreach (var binding in plan.Commands)
            {
                if (!binding.HasCanExecute)
                    continue;
                if (binding.RefreshOnAnyCommandStateChange)
                    anyCommand.Add(binding);
                else
                    filtered.Add(binding);
            }
            if (filtered.Count == 0 && anyCommand.Count == 0)
                return;

            sb.Append(Indent2).AppendLine("private void __OnViewCommandStateChanged(string __commandName)");
            sb.Append(Indent2).AppendLine("{");
            if (filtered.Count == 0)
            {
                foreach (var binding in anyCommand)
                    sb.Append(Indent3).Append(binding.RefreshMethod).AppendLine("();");
            }
            else
            {
                var order = new List<string>();
                var calls = new Dictionary<string, List<string>>(StringComparer.Ordinal);
                foreach (var binding in filtered)
                {
                    if (!calls.TryGetValue(binding.CommandTypeName, out var list))
                    {
                        list = new List<string>();
                        calls.Add(binding.CommandTypeName, list);
                        order.Add(binding.CommandTypeName);
                    }
                    list.Add(binding.RefreshMethod + "();");
                }

                sb.Append(Indent3).AppendLine("switch (__commandName)");
                sb.Append(Indent3).AppendLine("{");
                foreach (var name in order)
                {
                    sb.Append(Indent4).Append("case ").Append(SymbolDisplay.FormatLiteral(name, quote: true)).AppendLine(":");
                    foreach (var call in calls[name])
                        sb.Append(Indent4).Append(Indent1).AppendLine(call);
                    sb.Append(Indent4).AppendLine("    break;");
                }
                if (anyCommand.Count > 0)
                {
                    sb.Append(Indent4).AppendLine("default:");
                    foreach (var binding in anyCommand)
                        sb.Append(Indent4).Append(Indent1).Append(binding.RefreshMethod).AppendLine("();");
                    sb.Append(Indent4).AppendLine("    break;");
                }
                sb.Append(Indent3).AppendLine("}");
            }
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static void EmitDataBinding(StringBuilder sb, DataBindingPlan binding)
        {
            var field = binding.FieldName;
            sb.Append(Indent2).Append("private void ").Append(binding.RefreshMethod).AppendLine("()");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).Append("if (__view == null || ").Append(field).AppendLine(" == null)");
            sb.Append(Indent4).AppendLine("return;");

            var access = "__view." + UIBindingPlanner.EscapeIdentifier(binding.PropertyName);
            var display = binding.FormatLiteral != null
                ? "global::System.String.Format(" + binding.FormatLiteral + ", " + access + ")"
                : "global::System.Convert.ToString(" + access + ")";

            switch (binding.Control)
            {
                case ControlKind.Text:
                case ControlKind.TmpText:
                    sb.Append(Indent3).Append("var __text = ").Append(display).AppendLine(";");
                    sb.Append(Indent3).Append("if (").Append(field).AppendLine(".text != __text)");
                    sb.Append(Indent4).Append(field).AppendLine(".text = __text;");
                    break;
                case ControlKind.InputField:
                case ControlKind.TmpInputField:
                    sb.Append(Indent3).AppendLine("__uiUpdating = true;");
                    sb.Append(Indent3).AppendLine("try");
                    sb.Append(Indent3).AppendLine("{");
                    sb.Append(Indent4).Append("var __text = ").Append(display).AppendLine(";");
                    sb.Append(Indent4).Append("if (").Append(field).AppendLine(".text != __text)");
                    sb.Append(Indent4).Append(Indent1).Append(field).AppendLine(".text = __text;");
                    sb.Append(Indent3).AppendLine("}");
                    sb.Append(Indent3).AppendLine("finally");
                    sb.Append(Indent3).AppendLine("{");
                    sb.Append(Indent4).AppendLine("__uiUpdating = false;");
                    sb.Append(Indent3).AppendLine("}");
                    break;
                case ControlKind.Toggle:
                    sb.Append(Indent3).Append("var __value = ").Append(access).AppendLine(";");
                    sb.Append(Indent3).Append("if (").Append(field).AppendLine(".isOn != __value)");
                    sb.Append(Indent3).AppendLine("{");
                    sb.Append(Indent4).AppendLine("__uiUpdating = true;");
                    sb.Append(Indent4).AppendLine("try");
                    sb.Append(Indent4).AppendLine("{");
                    sb.Append(Indent4).Append(Indent1).Append(field).AppendLine(".isOn = __value;");
                    sb.Append(Indent4).AppendLine("}");
                    sb.Append(Indent4).AppendLine("finally");
                    sb.Append(Indent4).AppendLine("{");
                    sb.Append(Indent4).Append(Indent1).AppendLine("__uiUpdating = false;");
                    sb.Append(Indent4).AppendLine("}");
                    sb.Append(Indent3).AppendLine("}");
                    break;
                case ControlKind.Slider:
                    var sliderValue = binding.PropertyType.SpecialType == SpecialType.System_Single
                        ? access
                        : "(float)" + access;
                    sb.Append(Indent3).Append("var __value = ").Append(sliderValue).AppendLine(";");
                    sb.Append(Indent3).Append("if (").Append(field).AppendLine(".value != __value)");
                    sb.Append(Indent3).AppendLine("{");
                    sb.Append(Indent4).AppendLine("__uiUpdating = true;");
                    sb.Append(Indent4).AppendLine("try");
                    sb.Append(Indent4).AppendLine("{");
                    sb.Append(Indent4).Append(Indent1).Append(field).AppendLine(".value = __value;");
                    sb.Append(Indent4).AppendLine("}");
                    sb.Append(Indent4).AppendLine("finally");
                    sb.Append(Indent4).AppendLine("{");
                    sb.Append(Indent4).Append(Indent1).AppendLine("__uiUpdating = false;");
                    sb.Append(Indent4).AppendLine("}");
                    sb.Append(Indent3).AppendLine("}");
                    break;
            }

            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();

            if (binding.HandlerMethod != null && binding.WriteConversion != null)
                EmitDataHandler(sb, binding, field);
        }

        private static void EmitDataHandler(StringBuilder sb, DataBindingPlan binding, string field)
        {
            var parameterType = binding.Source == ValueSourceKind.String ? "string" : binding.Source == ValueSourceKind.Bool ? "bool" : "float";
            sb.Append(Indent2).Append("private void ").Append(binding.HandlerMethod).Append('(')
                .Append(parameterType).AppendLine(" __value)");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("if (__uiUpdating || __view == null)");
            sb.Append(Indent4).AppendLine("return;");
            var conversion = binding.WriteConversion!;
            if (conversion.ParseStatement != null)
                sb.Append(Indent3).AppendLine(conversion.ParseStatement);
            sb.Append(Indent3).Append("__view.").Append(UIBindingPlanner.EscapeIdentifier(binding.PropertyName))
                .Append(" = ").Append(conversion.Expression).AppendLine(";");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static void EmitCommandBinding(StringBuilder sb, CommandBindingPlan binding)
        {
            var field = binding.FieldName;
            EmitCommandHandler(sb, binding);
            if (!binding.HasCanExecute)
                return;

            sb.Append(Indent2).Append("private void ").Append(binding.RefreshMethod).AppendLine("()");
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).Append("if (__view == null || ").Append(field).AppendLine(" == null)");
            sb.Append(Indent4).AppendLine("return;");
            sb.Append(Indent3).Append("var __command = ").Append(CommandConstruction(binding, dispatch: false)).AppendLine(";");
            sb.Append(Indent3).AppendLine("var __canExecute = __command.CanExecute();");
            if (binding.HasRunningCheck)
            {
                sb.Append(Indent3).AppendLine("if (__canExecute && !__command.AllowConcurrentExecutions && __command.IsRunning)");
                sb.Append(Indent4).AppendLine("__canExecute = false;");
            }
            sb.Append(Indent3).Append("if (").Append(field).AppendLine(".interactable != __canExecute)");
            sb.Append(Indent4).Append(field).AppendLine(".interactable = __canExecute;");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static void EmitCommandHandler(StringBuilder sb, CommandBindingPlan binding)
        {
            var parameter = CommandEventParameter(binding.Control);
            var signature = string.IsNullOrEmpty(parameter) ? "()" : "(" + parameter + " __value)";
            sb.Append(Indent2).Append("private void ").Append(binding.HandlerMethod).AppendLine(signature);
            sb.Append(Indent2).AppendLine("{");
            sb.Append(Indent3).AppendLine("if (__view == null)");
            sb.Append(Indent4).AppendLine("return;");
            if (binding.Conversion != null)
            {
                if (binding.Conversion.ParseStatement != null)
                    sb.Append(Indent3).AppendLine(binding.Conversion.ParseStatement);
                if (binding.HasStoredValue)
                    sb.Append(Indent3).Append(binding.StoredValueFieldName).Append(" = ")
                        .Append(binding.Conversion.Expression).AppendLine(";");
            }

            var dispatcher = binding.Async ? "SendAsync" : "Send";
            sb.Append(Indent3).Append(BindingNamespace).Append(".GeneratedUIBindingRuntime.").Append(dispatcher)
                .Append("(this, __view, ").Append(CommandConstruction(binding, dispatch: true)).AppendLine(");");
            sb.Append(Indent2).AppendLine("}");
            sb.AppendLine();
        }

        private static string CommandEventParameter(ControlKind control)
        {
            switch (control)
            {
                case ControlKind.InputField:
                case ControlKind.TmpInputField:
                    return "string";
                case ControlKind.Toggle:
                    return "bool";
                case ControlKind.Slider:
                    return "float";
                default:
                    return string.Empty;
            }
        }

        private static string CommandConstruction(CommandBindingPlan binding, bool dispatch)
        {
            var takesView = dispatch ? binding.DispatchTakesView : binding.RefreshTakesView;
            var needsValue = dispatch ? binding.DispatchNeedsValue : binding.RefreshNeedsValue;
            var arguments = new List<string>();
            if (takesView)
                arguments.Add("__view");
            if (needsValue)
            {
                if (dispatch && !binding.HasStoredValue)
                    arguments.Add(binding.Conversion != null ? binding.Conversion.Expression : "__value");
                else
                    arguments.Add(binding.StoredValueFieldName);
            }
            return "new " + binding.CommandTypeExpression + "(" + string.Join(", ", arguments) + ")";
        }
    }
