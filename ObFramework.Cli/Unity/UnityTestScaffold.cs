using System.Xml.Linq;

namespace ObFramework.Cli.Unity;

internal static partial class UnityTestScaffold
{
    private const string SourceDirectory = "Assets/Scripts/Core";
    private const string AssemblyName = "Game.Core";
    private const string AssemblyFile = SourceDirectory + "/Game.Core.asmdef";
    private const string SettingsFile = "Tests/ObFramework.Unity.props";
    private const string SettingsLabel = "ObFrameworkUnityTestScaffold";
    private const string CoreProject = "Tests/Game.Core/Game.Core.csproj";
    private const string TestProject = "Tests/Game.Core.Tests/Game.Core.Tests.csproj";

    public static void Validate(string root)
    {
        var settingsPath = Path.Combine(root, SettingsFile);
        var initialized = File.Exists(settingsPath);
        if (initialized)
            ValidateSettings(settingsPath);
        else if (File.Exists(Path.Combine(root, CoreProject)) || File.Exists(Path.Combine(root, TestProject)))
            throw new InvalidOperationException("An existing .NET project occupies a scaffold path under Tests/.");

        var directory = Path.Combine(root, SourceDirectory);
        if (!Directory.Exists(directory)) return;

        var definitions = Directory.GetFiles(directory, "*.asmdef");
        if (definitions.Length == 0)
        {
            if (!initialized && Directory.EnumerateFileSystemEntries(directory).Any())
                throw new InvalidOperationException($"'{SourceDirectory}' already contains files and needs an engine-independent Game.Core.asmdef.");
            return;
        }

        var definitionPath = Path.Combine(root, AssemblyFile);
        if (definitions.Length != 1 || !File.Exists(definitionPath))
            throw new InvalidOperationException($"'{SourceDirectory}' must use Game.Core.asmdef as its assembly definition.");

        var definition = UnityProject.LoadObject(definitionPath);
        if (definition["name"]?.GetValue<string>() != AssemblyName || definition["noEngineReferences"]?.GetValue<bool>() != true)
            throw new InvalidOperationException($"'{AssemblyFile}' must name the assembly Game.Core and set noEngineReferences to true.");
    }

    public static void Install(string root, string fallbackVersion)
    {
        var layout = new NuGetLayout(root);
        var version = File.Exists(layout.Packages)
            ? (string?)XDocument.Load(layout.Packages).Root?.Elements("package").FirstOrDefault(package =>
                string.Equals((string?)package.Attribute("id"), "ObFramework", StringComparison.OrdinalIgnoreCase))?.Attribute("version")
            : null;
        var settings = new XElement("PropertyGroup", new XAttribute("Label", SettingsLabel),
            new XElement("ObFrameworkBusinessSource", SourceDirectory),
            new XElement("ObFrameworkBusinessAssembly", AssemblyName),
            new XElement("ObFrameworkPackageVersion", "[" + (version ?? fallbackVersion) + "]"));
        if (File.Exists(layout.Config))
        {
            var relativeConfig = Path.GetRelativePath(Path.Combine(root, "Tests"), layout.Config).Replace('\\', '/');
            settings.Add(new XElement("RestoreConfigFile",
                new XAttribute("Condition", "'$(RestoreConfigFile)' == ''"),
                "$(MSBuildThisFileDirectory)" + relativeConfig));
        }

        var settingsPath = Path.Combine(root, SettingsFile);
        var initialized = File.Exists(settingsPath);
        if (initialized) ValidateSettings(settingsPath);
        var settingsText = new XElement("Project", new XComment(" Generated by ob init. "), settings).ToString();
        WriteFile(settingsPath, settingsText, overwrite: initialized);

        WriteFile(Path.Combine(root, AssemblyFile), AssemblyDefinition);
        WriteFile(Path.Combine(root, SourceDirectory, "GameApplication.cs"), Application);
        WriteFile(Path.Combine(root, CoreProject), CoreProjectText);
        WriteFile(Path.Combine(root, TestProject), TestProjectText);
        WriteFile(Path.Combine(root, "Tests/Game.Core.Tests/GameApplicationTests.cs"), StartupTest);

        Console.WriteLine($"Init: .NET tests for '{SourceDirectory}' ready. Run dotnet test {TestProject}");
    }

    private static void ValidateSettings(string path)
    {
        var settings = XElement.Load(path).Elements("PropertyGroup")
            .FirstOrDefault(group => (string?)group.Attribute("Label") == SettingsLabel);
        if ((string?)settings?.Element("ObFrameworkBusinessSource") != SourceDirectory ||
            (string?)settings?.Element("ObFrameworkBusinessAssembly") != AssemblyName)
            throw new InvalidOperationException($"'{path}' does not belong to the {AssemblyName} test scaffold for '{SourceDirectory}'.");
    }

    private static void WriteFile(string path, string text, bool overwrite = false)
    {
        text += Environment.NewLine;
        if (File.Exists(path) && (!overwrite || File.ReadAllText(path) == text)) return;
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            File.WriteAllText(temporary, text);
            File.Move(temporary, path, overwrite);
        }
        catch (IOException) when (!overwrite && File.Exists(path))
        {
            // Another initialization already created this file.
        }
        finally
        {
            File.Delete(temporary);
        }
    }
}
